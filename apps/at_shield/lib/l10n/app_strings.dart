  String profileLabel(String name) => '$profileLabelPrefix$name';
  String sitesBlocked(int count) => '$sitesBlockedPrefix ($count)';
  String sitesEnabled(int enabled, int total) =>
      '$enabled $sitesEnabledOf $total $sitesEnabledSuffix';
  String attemptsLabel(int n) => attempts;
  String siteAdded(String domain) => '$siteAddedPrefix$domain$siteAddedSuffix';
  String siteRemoved(String domain) => '$domain$siteRemovedSuffix';
  String siteCopied(String name) => '$name$siteCopiedSuffix';
  String trayProtecting(String profile, String remaining) =>
      '$trayProtectingPrefix$profile$trayProtectingMid$remaining';
  String restoreSessionBody(String profile, String remaining) =>
      restoreSessionContent
          .replaceAll('{profile}', profile)
          .replaceAll('{remaining}', remaining);
  String protectionDay(String date) => '$protectionDayPrefix$date';
  String protectionProfile(String name) => '$protectionProfilePrefix$name';
  String duplicateProfileMsg(String name) =>
      '$duplicateProfilePrefix$name$duplicateProfileSuffix';
  String deleteProfileContent(String name) =>
      '$deleteProfileAskPrefix$name$deleteProfileAskSuffix';
  String deleteSiteTwitterMsg(String domain) =>
      deleteSiteTwitter.replaceAll('{domain}', domain);
  String deleteSiteConfirmMsg(String domain) =>
      deleteSiteConfirm.replaceAll('{domain}', domain);
  String siteAlreadyInList(String domain) => '$domain$siteAlreadySelected';
  String siteReactivatedInList(String domain) =>
      '$domain$siteReactivatedSelected';
  String attemptsIntro(int n) {
    if (n == 0) return noAttempts;
    if (n == 1) return attemptsIntroOne;
    return '$n $attemptsIntroManySuffix';
  }

  String durationLabel(int m) {
    if (m < 60) return '$m $durationMinSuffix';
    if (m % 60 == 0) {
      final h = m ~/ 60;
      return h == 1 ? durationHourSingular : '$h $durationHourPlural';
    }
    return '${m ~/ 60} $durationHourMin ${m % 60} $durationMinSuffix';
  }

  String durationClockLabel(int minutes, bool isPreset) =>
      isPreset ? clockPicker : '${durationLabel(minutes)} · $clockEdit';

